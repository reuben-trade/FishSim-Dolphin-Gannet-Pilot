def main():
    import os
    os.chdir(HERE)
    sys.path.insert(0,str(HERE))
    started=time.monotonic();namespace={'__name__':'__main__'};count=0
    for cell in cells:
        if cell['cell_type']!='code':continue
        count+=1;capture=io.StringIO()
        with contextlib.redirect_stdout(capture):exec(compile(''.join(cell['source']),f'<notebook cell {count}>','exec'),namespace)
        cell['execution_count']=count
        if capture.getvalue():cell['outputs'].append(dict(output_type='stream',name='stdout',text=capture.getvalue().splitlines(True)))
        if cell['metadata'].get('figure'):
            path=HERE/'outputs/current_figures'/(cell['metadata']['figure']+'.png')
            cell['outputs'].append(dict(output_type='display_data',data={'image/png':base64.b64encode(path.read_bytes()).decode(),
                'text/plain':[cell['metadata']['figure']]},metadata={}))
    assert 'fish_sim.cmodel' not in sys.modules
    import numpy as np
    import matplotlib.image as mpimg
    figures={}
    for name in ('fig1_model','fig2_development','fig3_replication','fig4_mechanism'):
        a,b=(HERE/directory/(name+'.png') for directory in ('outputs/current_figures','reference_figures_current'))
        equal=np.array_equal(mpimg.imread(a),mpimg.imread(b))
        if not equal:raise AssertionError(f'Figure differs from paper reference: {name}')
        figures[name]={'pixels_identical_to_reference':equal,'sha256':hashlib.sha256(a.read_bytes()).hexdigest()}
    notebook=dict(nbformat=4,nbformat_minor=5,metadata={'kernelspec':{'display_name':'Python 3','language':'python','name':'python3'},
        'language_info':{'name':'python','version':sys.version.split()[0]}},cells=cells)
    path=HERE/'FishSim_Professor_Notebook.ipynb';path.write_text(json.dumps(notebook,indent=1)+'\n')
    receipt=dict(status='passed',snapshot='2026-11-09',validated_cases=24,code_cells_executed=count,execution='all default code cells in a fresh Python process and clean namespace',
        notebook_sha256=hashlib.sha256(path.read_bytes()).hexdigest(),native_module_imported=False,native_steps=0,
        optional_model_smoke=('passed separately: validation/native_smoke.json; 800 native steps, two 0.5T cases'
            if (HERE/'validation/native_smoke.json').exists() else 'not yet executed; see separate receipt if present'),figures=figures,
        wall_seconds=time.monotonic()-started,python=sys.version.split()[0])
    (HERE/'validation').mkdir(exist_ok=True)
    (HERE/'validation/current_notebook_2026-11-09.json').write_text(json.dumps(receipt,indent=2)+'\n')
