markdown('''## What the model actually assumes

Each dolphin applies local pressure while moving around a tracked prey patch. It may launch one physically feasible strike after **2T of continuous proximity to any currently observed fish within radius 4.5**. It then handles a capture or recovers from a miss and repeats. The proximity clock is not a test that the pod has compacted the school. A fragmented school or isolated reachable fish remains eligible.

`nearest` ranks feasible targets by distance. `exposed` first prefers fewer observed neighbours within radius 2, then interception geometry and distance; this is a preference, not a sparse-fish-only rule. The same policy is used in D and DG. Dolphins do **not** explicitly wait for a bird dive or post-dive scatter in this experiment.

Gannets observe all underwater fish within their depth limit. DBSCAN-style density groups use radius 2 and at least four neighbours including self. A group is selected with probability proportional to accessible population, then a locally dense fish is targeted. Population weighting is distinct from density weighting.

The capture probability **0.7 applies at a resolved physical oral contact**, not per launch or dive. These runs were not calibrated to field dive-success observations; the field categories should not be interpreted as repeated attempts on the same fish. Space and time units are uncalibrated; 36T is not 36 seconds. There is no energy budget, evolutionary learning, numerical convergence claim or demonstration of reciprocal long-term cooperation.
''')
